function findAndReplace(data, search, replace) {
  const result = [];
  let i = 0;
  while (i <= data.length - search.length) {
    let match = true;
    for (let j = 0; j < search.length; j++) {
      if (data[i + j] !== search[j]) { match = false; break; }
    }
    if (match) {
      result.push(...replace);
      i += search.length;
    } else {
      result.push(data[i]);
      i++;
    }
  }
  while (i < data.length) { result.push(data[i]); i++; }
  return new Uint8Array(result);
}

const skipDirs = new Set(['node_modules', 'dist', '.git', 'build']);

function walkDir(dir) {
  const files = [];
  for (const entry of readdirSync(dir)) {
    if (skipDirs.has(entry)) continue;
    const full = join(dir, entry);
    const stat = statSync(full);
    if (stat.isDirectory()) {
      files.push(...walkDir(full));
    } else if (extensions.has(extname(full))) {
      files.push(full);
    }
  }
  return files;
}

console.log('=== Fix Mojibake - RDM Digital Hub ===');
console.log(`Buscando archivos en: ${root}`);

let totalFixed = 0;
let totalFiles = 0;

for (const file of walkDir(root)) {
  try {
    const original = new Uint8Array(readFileSync(file));
    let data = original;
    let changed = false;

    for (const [searchArr, replaceArr] of pairs) {
      const search = new Uint8Array(searchArr);
      const replace = new Uint8Array(replaceArr);
      if (data.length >= search.length) {
        const newData = findAndReplace(data, search, replace);
        if (newData.length !== data.length) {
          data = newData;
          changed = true;
        }
      }
    }

    if (changed) {
      writeFileSync(file, Buffer.from(data));
      totalFixed++;
      const saved = original.length - data.length;
      console.log(`  OK  ${file.split('/').pop()} (-${saved} bytes)`);
    }
    totalFiles++;
  } catch (err) {
    console.error(`  ERR ${file.split('/').pop()}: ${err.message}`);
  }
}

