            $data = $original
            $changed = $false

            foreach ($pair in $pairs) {
                $search = $pair[0]
                $replace = $pair[1]
                if ($data.Length -ge $search.Length) {
                    $newData = Find-And-Replace-Bytes -data $data -search $search -replace $replace
                    if ($newData.Length -ne $data.Length) {
                        $data = $newData
                        $changed = $true
                    }
                }
            }

            if ($changed) {
                [System.IO.File]::WriteAllBytes($file.FullName, $data)
                $totalFixed++
                $saved = $original.Length - $data.Length
                Write-Host "  OK  $($file.Name) (-$saved bytes)" -ForegroundColor Green
            }
            $totalFiles++
        }
        catch {
            Write-Host "  ERR $($file.Name): $_" -ForegroundColor Red
        }
    }
}

