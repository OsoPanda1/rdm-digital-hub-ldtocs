function Find-AndReplace-Bytes {
    param([byte[]]$data, [byte[]]$search, [byte[]]$replace)
    $result = New-Object System.Collections.Generic.List[byte]
    $i = 0
    while ($i -le $data.Length - $search.Length) {
        $match = $true
        for ($j = 0; $j -lt $search.Length; $j++) {
            if ($data[$i + $j] -ne $search[$j]) { $match = $false; break }
        }
        if ($match) {
            $result.AddRange($replace)
            $i += $search.Length
        } else {
            $result.Add($data[$i])
            $i++
        }
    }
    while ($i -lt $data.Length) { $result.Add($data[$i]); $i++ }
    return $result.ToArray()
}

